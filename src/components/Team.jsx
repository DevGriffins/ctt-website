const initials = (name) => {
  const parts = name.split(" ");
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
};

function Headshot({ person, mobile }) {
  const base = {
    flexShrink: "0",
    background: "linear-gradient(135deg,#34312F,#262423)",
    overflow: "hidden",
    ...(mobile
      ? { width: "88px", height: "108px", borderRadius: "12px" }
      : {
          aspectRatio: "4 / 5",
          borderRadius: "20px",
          clipPath: "polygon(0 0, calc(100% - 40px) 0, 100% 40px, 100% 100%, 0 100%)",
        }),
  };
  if (person.photo) {
    return (
      <div style={base}>
        <img
          src={person.photo}
          alt={`${person.name}, ${person.role}`}
          loading="lazy"
          style={{
            width: "100%",
            height: "100%",
            objectFit: "cover",
            objectPosition: person.photoPosition || "50% 25%",
            transform: person.photoZoom ? `scale(${person.photoZoom})` : undefined,
            transformOrigin: person.photoPosition || "50% 25%",
            display: "block",
          }}
        />
      </div>
    );
  }
  return (
    <div
      aria-hidden="true"
      style={{
        ...base,
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        fontSize: mobile ? "28px" : "56px",
        fontWeight: "700",
        letterSpacing: "0.02em",
        color: "#DFE21B",
      }}
    >
      {initials(person.name)}
    </div>
  );
}

